CREATE TABLE restaurant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    nit TEXT NOT NULL UNIQUE,
    address TEXT NOT NULL,
    phone VARCHAR(13) NOT NULL,
    logo_url TEXT NOT NULL,
    owner_id BIGINT NOT NULL,
    CONSTRAINT restaurant_name_not_only_digits CHECK (name !~ '^[0-9]+$'),
    CONSTRAINT nit_is_numeric CHECK (nit ~ '^[0-9]+$'),
    CONSTRAINT restaurant_phone_shape CHECK (phone ~ '^\+?[0-9]+$' AND char_length(phone) <= 13)
);

CREATE INDEX restaurant_name_idx ON restaurant (name);

CREATE TABLE dish (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurant (id),
    name TEXT NOT NULL,
    price INTEGER NOT NULL,
    description TEXT NOT NULL,
    image_url TEXT NOT NULL,
    category TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT price_is_positive CHECK (price > 0)
);

CREATE INDEX dish_restaurant_category_idx ON dish (restaurant_id, category);

CREATE TABLE customer_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    restaurant_id BIGINT NOT NULL REFERENCES restaurant (id),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    assigned_employee_id BIGINT,
    pin_hash VARCHAR(72),
    CONSTRAINT order_status_known CHECK (
        status IN ('PENDING', 'IN_PREPARATION', 'READY', 'DELIVERED', 'CANCELLED')
    )
);

CREATE INDEX customer_order_restaurant_status_idx
    ON customer_order (restaurant_id, status);

CREATE UNIQUE INDEX customer_order_one_active_idx
    ON customer_order (customer_id)
    WHERE status IN ('PENDING', 'IN_PREPARATION', 'READY');

CREATE TABLE order_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES customer_order (id),
    dish_id BIGINT NOT NULL REFERENCES dish (id),
    quantity INTEGER NOT NULL,
    CONSTRAINT quantity_is_positive CHECK (quantity > 0),
    CONSTRAINT one_line_per_dish UNIQUE (order_id, dish_id)
);
